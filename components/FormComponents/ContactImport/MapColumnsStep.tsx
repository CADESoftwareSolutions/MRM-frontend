import { useId } from "react";
import { AlertCircle, Download, Loader2 } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import type { ContactImportTemplate } from "@/hooks/useImportTemplates";
import { MatchBadge } from "../../AccountingComponents/Revenue/import/MatchBadge";
import { SECTION_HEADER_CLASS, useImportTheme } from "../../AccountingComponents/Revenue/import/importTheme";
import { ImportSelect } from "./ImportSelect";
import {
  ADDRESS_TYPES,
  ColumnReview,
  ColumnTarget,
  DEFAULT_PHONE_TYPE,
  FIELD_GROUPS,
  FIELD_LABELS,
  FIELD_NOTES,
  FieldKey,
  ImportSettings,
  MatchAction,
  PHONE_TYPES,
  ReviewCounts,
  SKIP,
  isAddressPart,
  plural,
  sampleText,
} from "./contactImportModel";

export interface QuickCheck {
  counts: ReviewCounts;
  /** "3 missing Name, 2 bad Zip" */
  errorSummary: string;
  loading: boolean;
  error: string | null;
  onRetry: () => void;
}

export interface MapColumnsStepProps {
  columns: ColumnReview[];
  settings: ImportSettings;
  onTargetChange: (columnIndex: number, target: ColumnTarget) => void;
  onSettingsChange: (patch: Partial<ImportSettings>) => void;
  classificationOptions: string[];
  templates: ContactImportTemplate[];
  templateId: string | null;
  onTemplateChange: (templateId: string | null) => void;
  saveMapping: boolean;
  onSaveMappingChange: (save: boolean) => void;
  mappingName: string;
  onMappingNameChange: (name: string) => void;
  onDownloadTemplate: () => void;
  /** What has to change before continuing. */
  problems: string[];
  quickCheck: QuickCheck;
}

const DEFAULT_TYPE = "__default__";
const BY_NAME = "__by_name__";

const MATCH_ACTIONS: { value: MatchAction; label: string }[] = [
  { value: "skip", label: "Skip the row" },
  { value: "fill", label: "Fill in blank fields only" },
  { value: "overwrite", label: "Overwrite fields and addresses that differ" },
];

const MATCH_ACTION_SUMMARY: Record<MatchAction, string> = {
  skip: "they'll be skipped",
  fill: "only their empty fields and missing addresses are filled in",
  overwrite: "fields and whole addresses that differ are replaced",
};

const FIELD_SELECT_GROUPS = FIELD_GROUPS.map((group) => ({
  label: group.label,
  options: group.fields.map((field) => ({
    value: field,
    label: field === "name" ? `${FIELD_LABELS.name} *` : FIELD_LABELS[field],
  })),
}));

const SKIP_OPTION = [{ value: "skip", label: FIELD_LABELS.skip }];
const PHONE_TYPE_OPTIONS = PHONE_TYPES.map((type) => ({ value: type, label: type }));

/** Keeps the address or phone type when switching between parts that have one. */
const retarget = (previous: ColumnTarget, field: FieldKey): ColumnTarget => {
  if (isAddressPart(field)) return { field, type: isAddressPart(previous.field) ? previous.type : null };
  if (field === "phone") return { field, type: previous.field === "phone" ? previous.type : DEFAULT_PHONE_TYPE };
  return { field, type: null };
};

const ColumnStatus = ({ review }: { review: ColumnReview }) => {
  const { state, mapping, column, duplicateOf } = review;
  const note =
    state === "matched"
      ? FIELD_NOTES[mapping.target.field]
      : state === "duplicate"
        ? `Also mapped from “${duplicateOf}”`
        : column.nameId
          ? "Name IDs are generated by CADE"
          : undefined;
  return (
    <div className="flex flex-wrap items-center gap-x-2 gap-y-1">
      {state === "matched" && (
        <MatchBadge
          tone="green"
          title={
            mapping.source === "template"
              ? "From your saved mapping"
              : mapping.source === "user"
                ? "Chosen here"
                : "Matched by the column name"
          }
        >
          Matched
        </MatchBadge>
      )}
      {state === "skipped" && <MatchBadge tone="gray">Skipped</MatchBadge>}
      {state === "notMapped" && <MatchBadge tone="yellow">Not mapped</MatchBadge>}
      {state === "duplicate" && <MatchBadge tone="red">Mapped twice</MatchBadge>}
      {note && <span className="text-xs text-white/70">{note}</span>}
    </div>
  );
};

const TargetPicker = ({
  review,
  settings,
  onChange,
}: {
  review: ColumnReview;
  settings: ImportSettings;
  onChange: (target: ColumnTarget) => void;
}) => {
  const { target } = review.mapping;
  const name = review.column.header;
  const hasAddressType = isAddressPart(target.field);
  const hasPhoneType = target.field === "phone";
  return (
    <div className="flex items-center gap-2">
      <ImportSelect
        value={target.field}
        onChange={(field) => onChange(field === "skip" ? SKIP : retarget(target, field as FieldKey))}
        options={SKIP_OPTION}
        groups={FIELD_SELECT_GROUPS}
        dashed={target.field === "skip"}
        invalid={review.state === "duplicate"}
        className="min-w-[180px] flex-1"
        aria-label={`CADE field for ${name}`}
      />
      {hasAddressType && (
        <ImportSelect
          value={target.type ?? DEFAULT_TYPE}
          onChange={(type) => onChange({ field: target.field, type: type === DEFAULT_TYPE ? null : type })}
          options={[
            { value: DEFAULT_TYPE, label: `${settings.defaultAddressType} (default)` },
            ...ADDRESS_TYPES.map((type) => ({ value: type, label: type })),
          ]}
          className="w-[160px] shrink-0"
          aria-label={`Address type for ${name}`}
        />
      )}
      {hasPhoneType && (
        <ImportSelect
          value={target.type ?? DEFAULT_PHONE_TYPE}
          onChange={(type) => onChange({ field: "phone", type })}
          options={PHONE_TYPE_OPTIONS}
          className="w-[160px] shrink-0"
          aria-label={`Phone type for ${name}`}
        />
      )}
    </div>
  );
};

const SettingsLabel = ({ htmlFor, children }: { htmlFor?: string; children: string }) => (
  <label htmlFor={htmlFor} className="mb-1 block text-sm font-semibold text-white">
    {children}
  </label>
);

export const MapColumnsStep = ({
  columns,
  settings,
  onTargetChange,
  onSettingsChange,
  classificationOptions,
  templates,
  templateId,
  onTemplateChange,
  saveMapping,
  onSaveMappingChange,
  mappingName,
  onMappingNameChange,
  onDownloadTemplate,
  problems,
  quickCheck,
}: MapColumnsStepProps) => {
  const theme = useImportTheme();
  const ids = useId();
  const th = `px-3.5 py-2.5 text-left text-xs font-semibold uppercase tracking-wider whitespace-nowrap ${theme.headerText}`;
  const { counts } = quickCheck;
  const ready = counts.new + counts.update;

  return (
    <div className="flex flex-wrap items-start gap-5">
      <div className="min-w-0 flex-[999_1_600px]">
        <div className="overflow-x-auto rounded-xl border border-purple-300/20 bg-white/5">
          <table className="w-full min-w-[860px] text-sm">
            <thead>
              <tr className="border-b border-purple-300/20">
                <th className={th}>Spreadsheet column</th>
                <th className={th}>First row</th>
                <th className={`${th} w-7`}>
                  <span className="sr-only">Maps to</span>
                </th>
                <th className={`${th} w-[360px]`}>CADE field</th>
                <th className={th}>Status</th>
              </tr>
            </thead>
            <tbody>
              {columns.map((review) => {
                const sample = sampleText(review);
                return (
                  <tr key={review.column.index} className={`border-b last:border-0 ${theme.rowBorder}`}>
                    <td className="px-3.5 py-1.5 font-semibold whitespace-nowrap text-white">{review.column.header}</td>
                    <td className="max-w-[220px] truncate px-3.5 py-1.5 text-white/70" title={sample || undefined}>
                      {sample || "—"}
                    </td>
                    <td className="px-1 py-1.5 text-white/60" aria-hidden>
                      →
                    </td>
                    <td className="px-3.5 py-1.5">
                      <TargetPicker
                        review={review}
                        settings={settings}
                        onChange={(target) => onTargetChange(review.column.index, target)}
                      />
                    </td>
                    <td className="px-3.5 py-1.5">
                      <ColumnStatus review={review} />
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>
      </div>

      <aside aria-label="Import settings" className="flex max-w-full flex-[1_1_300px] flex-col gap-3">
        <section className="flex flex-col gap-3 rounded-xl border border-purple-300/20 bg-white/5 px-4 py-3.5">
          <h3 className={SECTION_HEADER_CLASS}>Import Settings</h3>

          {templates.length > 0 && (
            <div>
              <SettingsLabel htmlFor={`${ids}-template`}>Saved mapping</SettingsLabel>
              <ImportSelect
                id={`${ids}-template`}
                value={templateId ?? BY_NAME}
                onChange={(value) => onTemplateChange(value === BY_NAME ? null : value)}
                options={[
                  { value: BY_NAME, label: "None (match by column name)" },
                  ...templates.map((t) => ({ value: t.id, label: t.name })),
                ]}
              />
            </div>
          )}

          <div>
            <SettingsLabel htmlFor={`${ids}-classification`}>If Classification Type is blank</SettingsLabel>
            <ImportSelect
              id={`${ids}-classification`}
              value={settings.defaultClassification}
              onChange={(value) => onSettingsChange({ defaultClassification: value })}
              options={classificationOptions.map((type) => ({ value: type, label: type }))}
            />
          </div>

          <div>
            <SettingsLabel htmlFor={`${ids}-address-type`}>If Address Type is blank</SettingsLabel>
            <ImportSelect
              id={`${ids}-address-type`}
              value={settings.defaultAddressType}
              onChange={(value) => onSettingsChange({ defaultAddressType: value })}
              options={ADDRESS_TYPES.map((type) => ({ value: type, label: type }))}
            />
            <p className="form-help-text mt-1 text-xs">
              For address columns without a type, like “Addr 1” or “City”.
            </p>
          </div>

          <fieldset className="m-0 border-0 p-0">
            <legend className="mb-0.5 p-0 text-sm font-semibold text-white">When a row matches an existing contact</legend>
            <p className="form-help-text mb-1 text-xs">Matched by Tax ID, then Name + Zip.</p>
            {MATCH_ACTIONS.map((action) => (
              <label key={action.value} className="flex cursor-pointer items-start gap-2 py-1.5 text-sm text-white">
                <input
                  type="radio"
                  name={`${ids}-on-match`}
                  checked={settings.onMatch === action.value}
                  onChange={() => onSettingsChange({ onMatch: action.value })}
                  className="mt-0.5 size-4 shrink-0 cursor-pointer accent-purple-600"
                />
                {action.label}
              </label>
            ))}
            <ul className="form-help-text mt-0.5 list-disc space-y-0.5 pl-4 text-xs">
              <li>Fill in blank fields only: fills only empty fields and addresses the contact doesn&apos;t have yet. It never renames a contact or changes an address already on file.</li>
              <li>Overwrite: replaces fields that differ, and replaces a whole address when it differs (never part of one).</li>
              <li>Both: Comments are added to the contact&apos;s notes, classification types are added and never removed, and Name IDs are never imported. A blank cell never clears anything.</li>
            </ul>
          </fieldset>

          <div className="flex flex-col gap-1.5 border-t border-purple-300/20 pt-2.5">
            <label className="flex cursor-pointer items-start gap-2 text-sm text-white">
              <input
                type="checkbox"
                checked={saveMapping}
                onChange={(event) => onSaveMappingChange(event.target.checked)}
                className="mt-0.5 size-4 shrink-0 cursor-pointer accent-purple-600"
              />
              Save this mapping as
            </label>
            <Input
              value={mappingName}
              onChange={(event) => onMappingNameChange(event.target.value)}
              disabled={!saveMapping}
              aria-label="Mapping name"
              placeholder="e.g. Operator owner export"
              className="h-9 bg-white/5 border-purple-300/30 text-white"
            />
            <p className="form-help-text text-xs">Offered again when a file with the same columns is uploaded.</p>
          </div>

          <button
            type="button"
            onClick={onDownloadTemplate}
            className={`inline-flex items-center gap-1.5 self-start text-sm ${theme.link}`}
          >
            <Download className="size-3.5" aria-hidden />
            Download a blank template (.csv)
          </button>
        </section>

        <section aria-live="polite" className="rounded-xl border border-purple-300/20 bg-white/5 px-4 py-3.5">
          <h3 className={`${SECTION_HEADER_CLASS} mb-2`}>Quick Check</h3>
          {quickCheck.loading ? (
            <p className="flex items-center gap-2 text-sm text-white/70">
              <Loader2 className="size-4 animate-spin" aria-hidden />
              Checking your existing contacts…
            </p>
          ) : quickCheck.error ? (
            <div className={`flex flex-col items-start gap-2 rounded-lg border p-3 text-sm ${theme.errorBox}`}>
              <span>Your contacts couldn&apos;t be loaded to check for matches: {quickCheck.error}</span>
              <Button
                variant="outline"
                size="sm"
                onClick={quickCheck.onRetry}
                className={`cursor-pointer ${theme.outlineButton}`}
              >
                Try again
              </Button>
            </div>
          ) : (
            <>
              <div className="flex flex-wrap gap-1.5">
                <MatchBadge tone="green">{ready.toLocaleString("en-US")} ready</MatchBadge>
                {counts.error > 0 && <MatchBadge tone="red">{plural(counts.error, "error")}</MatchBadge>}
                {counts.matched > 0 && (
                  <MatchBadge tone="yellow">{plural(counts.matched, "existing contact")}</MatchBadge>
                )}
              </div>
              {counts.error > 0 && (
                <p className="mt-2 text-xs text-white/70">
                  Errors: {quickCheck.errorSummary}. You can fix them in the spreadsheet or skip them on the next step.
                </p>
              )}
              {counts.matched > 0 && (
                <p className="mt-2 text-xs text-white/70">
                  {plural(counts.matched, "row")} {counts.matched === 1 ? "matches a contact" : "match contacts"} already in
                  CADE; {MATCH_ACTION_SUMMARY[settings.onMatch]}.
                </p>
              )}
            </>
          )}
          {problems.length > 0 && (
            <ul className={`mt-2 flex flex-col gap-1 text-xs ${theme.badText}`}>
              {problems.map((problem) => (
                <li key={problem} className="flex items-start gap-1.5">
                  <AlertCircle className="mt-px size-3.5 shrink-0" aria-hidden />
                  {problem}
                </li>
              ))}
            </ul>
          )}
        </section>
      </aside>
    </div>
  );
};

export default MapColumnsStep;
