import { useEffect, useMemo, useRef, useState } from "react";
import { Info, Upload } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Card } from "@/components/ui/card";
import { ContactImportJob, ExistingContact, useContactImport } from "@/hooks/useContactImport";
import { ContactImportTemplate, useImportTemplates } from "@/hooks/useImportTemplates";
import { PRIMARY_BUTTON_CLASS, useImportTheme } from "../../AccountingComponents/Revenue/import/importTheme";
import { ContactImportStep, ContactImportStepper } from "./ContactImportStepper";
import { ImportRun, ImportStep, SkippedBreakdown } from "./ImportStep";
import { MapColumnsStep } from "./MapColumnsStep";
import { IncludedReviewRow, ReviewStep } from "./ReviewStep";
import { UploadStep } from "./UploadStep";
import { fileProblem, readCsvText } from "@/lib/csv";
import { baseFileName, downloadCsv } from "./contactImportFile";
import {
  BUILT_IN_CLASSIFICATIONS,
  ColumnMappings,
  ColumnTarget,
  DEFAULT_SETTINGS,
  ImportSettings,
  ParsedSheet,
  autoMap,
  buildReviewRows,
  buildRowsToFixCsv,
  buildTemplateCsv,
  canImport,
  countRows,
  mappingProblems,
  parseContactSheet,
  plural,
  readRecords,
  reviewColumns,
  summarizeErrors,
  templateColumns,
} from "./contactImportModel";

export interface ContactImportProps {
  /** Back to the Contacts list. */
  onClose: () => void;
}

const NO_COLUMNS: ParsedSheet["columns"] = [];

const BANNERS: Record<ContactImportStep, string> = {
  1: "Import contacts from a spreadsheet, one contact per row. Name IDs are generated by CADE, so an Owner # or other ID column is never imported.",
  2: "Each column was matched to a CADE field by its name. Check the matches, choose a field for anything Not mapped, and decide what happens when a row matches a contact already in CADE.",
  3: "Rows marked Error can't be imported until they're fixed in the spreadsheet. Untick any New or Update row you don't want.",
  4: "Contacts are created and updated a few rows at a time. A row that fails doesn't stop the rest; failures are listed at the end.",
};

/** A template brings the default types, never what happens to matching contacts. */
const withTemplateSettings = (
  current: ImportSettings,
  template: ContactImportTemplate | null,
  onMatch: ImportSettings["onMatch"],
): ImportSettings => ({
  defaultClassification: template?.settings.defaultClassification ?? current.defaultClassification,
  defaultAddressType: template?.settings.defaultAddressType ?? current.defaultAddressType,
  onMatch,
});

const HAND_ENTRY_LABEL = "Contact saved — add the address/phone by hand";

const downloadTemplate = () => downloadCsv("contacts-import-template.csv", buildTemplateCsv());

export const ContactImport = ({ onClose }: ContactImportProps) => {
  const theme = useImportTheme();
  const { existing, existingLoading, existingError, reloadExisting, customClassifications, runImport } =
    useContactImport();
  const { templates, saveTemplate, findTemplate } = useImportTemplates();

  const [step, setStep] = useState<ContactImportStep>(1);
  const [fileName, setFileName] = useState<string | null>(null);
  const [sheet, setSheet] = useState<ParsedSheet | null>(null);
  const [reading, setReading] = useState(false);
  const [fileError, setFileError] = useState<string | null>(null);
  const [mappings, setMappings] = useState<ColumnMappings>({});
  const [settings, setSettings] = useState<ImportSettings>(DEFAULT_SETTINGS);
  const [templateId, setTemplateId] = useState<string | null>(null);
  const [saveMapping, setSaveMapping] = useState(true);
  const [mappingName, setMappingName] = useState("");
  const [includeOverrides, setIncludeOverrides] = useState<Record<number, boolean>>({});
  const [run, setRun] = useState<ImportRun | null>(null);
  const [rowsToFix, setRowsToFix] = useState<{ rowNumber: number; message: string }[]>([]);
  const [rowsToFinish, setRowsToFinish] = useState<{ rowNumber: number; message: string }[]>([]);
  const [preparing, setPreparing] = useState(false);
  const [importNotice, setImportNotice] = useState<string | null>(null);
  const readToken = useRef(0);
  const stopRef = useRef(false);

  useEffect(() => {
    window.scrollTo({ top: 0, behavior: "smooth" });
  }, [step]);

  // Leaving the page mid-import stops it after the rows already in progress.
  useEffect(
    () => () => {
      stopRef.current = true;
    },
    [],
  );

  const columns = sheet && !sheet.fatal ? sheet.columns : NO_COLUMNS;
  const columnReviews = useMemo(() => reviewColumns(columns, mappings, settings), [columns, mappings, settings]);
  const problems = useMemo(() => mappingProblems(columnReviews, settings), [columnReviews, settings]);
  const records = useMemo(
    () => (sheet && !sheet.fatal ? readRecords(sheet, columnReviews, settings, customClassifications) : []),
    [sheet, columnReviews, settings, customClassifications],
  );
  const reviewRows = useMemo(() => buildReviewRows(records, existing, settings), [records, existing, settings]);
  const rows = useMemo<IncludedReviewRow[]>(
    () => reviewRows.map((row) => ({ ...row, included: canImport(row) && (includeOverrides[row.rowNumber] ?? true) })),
    [reviewRows, includeOverrides],
  );
  const counts = useMemo(() => countRows(reviewRows), [reviewRows]);
  const selected = rows.filter((row) => row.included);
  const matchedColumns = columnReviews.filter((review) => review.state === "matched").length;
  const classificationOptions = useMemo(
    () => Array.from(new Set([...BUILT_IN_CLASSIFICATIONS, ...customClassifications])),
    [customClassifications],
  );
  const appliedTemplate = templates.find((t) => t.id === templateId) ?? null;

  const resetFile = () => {
    setSheet(null);
    setMappings({});
    setIncludeOverrides({});
    setTemplateId(null);
  };

  const handleFile = async (file: File) => {
    const token = ++readToken.current;
    const problem = fileProblem(file);
    setFileName(file.name);
    resetFile();
    setFileError(problem);
    if (problem) return;
    setReading(true);
    try {
      const text = await readCsvText(file);
      if (token !== readToken.current) return;
      const parsed = parseContactSheet(text);
      setSheet(parsed);
      if (parsed.fatal) return;
      const template = findTemplate(parsed.columns.map((column) => column.key));
      const nextSettings = withTemplateSettings(settings, template, "fill");
      setSettings(nextSettings);
      setMappings(autoMap(parsed.columns, nextSettings, template));
      setTemplateId(template?.id ?? null);
      setMappingName(template?.name ?? baseFileName(file.name));
    } catch {
      if (token === readToken.current) setFileError(`Couldn't read ${file.name}. Save it again as CSV and retry.`);
    } finally {
      if (token === readToken.current) setReading(false);
    }
  };

  const chooseTemplate = (id: string | null) => {
    const template = templates.find((t) => t.id === id) ?? null;
    const nextSettings = withTemplateSettings(settings, template, settings.onMatch);
    setSettings(nextSettings);
    setMappings(autoMap(columns, nextSettings, template));
    setTemplateId(template?.id ?? null);
    setMappingName(template?.name ?? (fileName ? baseFileName(fileName) : ""));
  };

  const changeTarget = (columnIndex: number, target: ColumnTarget) =>
    setMappings((current) => ({ ...current, [columnIndex]: { target, source: "user" } }));

  const toggleRows = (rowNumbers: number[], included: boolean) =>
    setIncludeOverrides((current) => {
      const next = { ...current };
      for (const rowNumber of rowNumbers) next[rowNumber] = included;
      return next;
    });

  const startImport = async () => {
    if (!selected.length || run?.running || preparing) return;
    setImportNotice(null);
    setPreparing(true);
    let fresh: ExistingContact[];
    try {
      const refreshed = await reloadExisting();
      if (refreshed.error || !refreshed.data) throw refreshed.error ?? new Error("No contacts returned");
      fresh = refreshed.data;
    } catch {
      setPreparing(false);
      setImportNotice("Your contacts couldn't be refreshed just before importing, so nothing was imported. Try again.");
      return;
    }
    setPreparing(false);
    const freshRows = buildReviewRows(records, fresh, settings);
    const planOf = (row: { status: string; match: ExistingContact | null; plan: unknown }) =>
      JSON.stringify([row.status, row.match?.id ?? null, row.plan]);
    const freshByRow = new Map(freshRows.map((row) => [row.rowNumber, row]));
    const changed = selected.some((row) => {
      const latest = freshByRow.get(row.rowNumber);
      return !latest || planOf(latest) !== planOf(row);
    });
    if (changed) {
      setImportNotice(
        "Contacts changed while you were reviewing, so nothing was imported. The review above is updated; check it and import again.",
      );
      return;
    }

    const jobs: ContactImportJob[] = selected
      .filter((row) => row.plan)
      .map((row) => ({ rowNumber: row.rowNumber, name: row.record.name, plan: row.plan! }));
    // Counted now: once contacts are created, the rows would match them and read differently.
    const skipped: SkippedBreakdown = {
      errors: counts.error,
      leftOut: rows.filter((row) => canImport(row) && !row.included).length,
      matched: reviewRows.filter((row) => row.skipKind === "matched").length,
      duplicates: reviewRows.filter((row) => row.skipKind === "duplicate").length,
      unchanged: reviewRows.filter((row) => row.skipKind === "unchanged").length,
    };
    const errorRows = reviewRows
      .filter((row) => row.status === "error")
      .map((row) => ({ rowNumber: row.rowNumber, message: row.errors.map((e) => e.message).join("; ") }));

    if (saveMapping && mappingName.trim()) {
      const template = await saveTemplate({
        name: mappingName,
        columns: templateColumns(columns, mappings),
        settings: { defaultClassification: settings.defaultClassification, defaultAddressType: settings.defaultAddressType },
      });
      setTemplateId(template.id);
    }

    stopRef.current = false;
    setRowsToFix(errorRows);
    setRowsToFinish([]);
    setRun({ total: jobs.length, done: 0, running: true, stopping: false, outcomes: [], skipped, fatal: null });
    setStep(4);
    try {
      const outcomes = await runImport(jobs, {
        fileName: fileName ?? "a spreadsheet",
        onProgress: (done) => setRun((current) => current && { ...current, done }),
        shouldStop: () => stopRef.current,
      });
      const failedRows = outcomes
        .filter((o) => o.result === "failed")
        .map((o) => ({ rowNumber: o.rowNumber, message: o.error ?? "Not saved" }));
      // Saved contacts stay out of the rows to fix: uploading them again would create them twice.
      const savedRows = outcomes
        .filter((o) => o.result !== "failed" && o.problems.length > 0)
        .map((o) => ({
          rowNumber: o.rowNumber,
          message: `${HAND_ENTRY_LABEL} (${o.nameId}): ${o.problems.join("; ")}`,
        }));
      setRowsToFix([...errorRows, ...failedRows]);
      setRowsToFinish(savedRows);
      setRun((current) => current && { ...current, running: false, stopping: false, outcomes });
    } catch (error) {
      setRun(
        (current) =>
          current && { ...current, running: false, stopping: false, fatal: (error as Error).message || "Unknown error" },
      );
    }
  };

  const stopImport = () => {
    stopRef.current = true;
    setRun((current) => current && { ...current, stopping: true });
  };

  const startOver = () => {
    readToken.current += 1;
    setStep(1);
    setFileName(null);
    setFileError(null);
    setReading(false);
    resetFile();
    setRun(null);
    setRowsToFix([]);
    setRowsToFinish([]);
    setImportNotice(null);
  };

  const running = !!run?.running;
  const finished = !!run && !run.running;
  const sheetReady = !!sheet && !sheet.fatal && !reading;
  const matchesReady = !existingLoading && !existingError;
  const selectedNew = selected.filter((row) => row.status === "new").length;

  const stepNotes: [string, string, string, string] = [
    fileName && sheet && !sheet.fatal ? `${fileName} · ${plural(sheet.rows.length, "row")}` : "Spreadsheet saved as .csv",
    step < 2 ? "A CADE field for each column" : `${matchedColumns} of ${columns.length} matched`,
    step < 3 ? "Errors and existing matches" : `${plural(run ? run.total : selected.length, "row")} selected`,
    run ? (running ? `${run.done.toLocaleString("en-US")} of ${run.total.toLocaleString("en-US")} done` : "Finished") : "Create and update records",
  ];

  const importLabel =
    selectedNew === selected.length
      ? `Import ${plural(selected.length, "contact")}`
      : selectedNew === 0
        ? `Update ${plural(selected.length, "contact")}`
        : `Import ${plural(selected.length, "contact")} (${selectedNew.toLocaleString("en-US")} new, ${(
            selected.length - selectedNew
          ).toLocaleString("en-US")} updates)`;

  return (
    <Card className="bg-white/10 backdrop-blur-md border-purple-300/30 gap-4 px-5 py-4">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <h2 className="flex items-center gap-2 text-lg font-semibold text-white">
          <Upload className="size-5" aria-hidden />
          Import Contacts from Excel
        </h2>
        <Button
          variant="ghost"
          onClick={onClose}
          disabled={running}
          className="text-purple-300 hover:text-purple-100 hover:bg-purple-500/20 cursor-pointer"
        >
          Back to Contacts
        </Button>
      </div>

      <ContactImportStepper current={step} notes={stepNotes} onSelect={run ? undefined : setStep} />

      <div className="flex items-start gap-2 rounded-lg border border-blue-300/30 bg-blue-500/10 p-3">
        <Info className="mt-0.5 size-4 shrink-0 text-blue-300" aria-hidden />
        <p className="text-sm text-blue-200">{BANNERS[step]}</p>
      </div>

      {step === 1 && (
        <UploadStep
          fileName={fileName}
          sheet={sheet}
          reading={reading}
          fileError={fileError}
          templateName={appliedTemplate?.name ?? null}
          onFile={(file) => void handleFile(file)}
          onDownloadTemplate={downloadTemplate}
        />
      )}

      {step === 2 && (
        <MapColumnsStep
          columns={columnReviews}
          settings={settings}
          onTargetChange={changeTarget}
          onSettingsChange={(patch) => setSettings((current) => ({ ...current, ...patch }))}
          classificationOptions={classificationOptions}
          templates={templates}
          templateId={templateId}
          onTemplateChange={chooseTemplate}
          saveMapping={saveMapping}
          onSaveMappingChange={setSaveMapping}
          mappingName={mappingName}
          onMappingNameChange={setMappingName}
          onDownloadTemplate={downloadTemplate}
          problems={problems}
          quickCheck={{
            counts,
            errorSummary: summarizeErrors(reviewRows),
            loading: existingLoading,
            error: existingError,
            onRetry: () => void reloadExisting(),
          }}
        />
      )}

      {step === 3 && importNotice && (
        <p role="alert" className={`rounded-lg border p-3 text-sm ${theme.warnBox}`}>
          {importNotice}
        </p>
      )}

      {step === 3 && <ReviewStep rows={rows} onToggle={toggleRows} />}

      {step === 4 && run && (
        <ImportStep
          run={run}
          onDownloadRowsToFix={
            finished && rowsToFix.length && sheet
              ? () =>
                  downloadCsv(
                    `${baseFileName(fileName ?? "contacts")}-rows-to-fix.csv`,
                    buildRowsToFixCsv(sheet, rowsToFix),
                  )
              : null
          }
          onDownloadRowsToFinish={
            finished && rowsToFinish.length && sheet
              ? () =>
                  downloadCsv(
                    `${baseFileName(fileName ?? "contacts")}-saved-add-by-hand.csv`,
                    buildRowsToFixCsv(sheet, rowsToFinish),
                  )
              : null
          }
        />
      )}

      <div className="flex flex-wrap justify-between gap-3 border-t border-purple-300/30 pt-3">
        {step === 1 && (
          <Button variant="outline" onClick={onClose} className={`cursor-pointer ${theme.outlineButton}`}>
            Cancel
          </Button>
        )}
        {(step === 2 || step === 3) && (
          <Button
            variant="outline"
            onClick={() => setStep((s) => (s - 1) as ContactImportStep)}
            className={`cursor-pointer ${theme.outlineButton}`}
          >
            Back
          </Button>
        )}
        {step === 4 && running && (
          <Button
            variant="outline"
            onClick={stopImport}
            disabled={run?.stopping}
            className={`cursor-pointer ${theme.outlineButton}`}
          >
            Stop import
          </Button>
        )}
        {step === 4 && finished && (
          <Button variant="outline" onClick={startOver} className={`cursor-pointer ${theme.outlineButton}`}>
            Import another file
          </Button>
        )}

        {step === 1 && (
          <Button disabled={!sheetReady} onClick={() => setStep(2)} className={PRIMARY_BUTTON_CLASS}>
            Continue to Map columns
          </Button>
        )}
        {step === 2 && (
          <Button
            disabled={problems.length > 0 || !matchesReady}
            onClick={() => setStep(3)}
            className={PRIMARY_BUTTON_CLASS}
          >
            Continue to Review
          </Button>
        )}
        {step === 3 && (
          <Button
            disabled={!selected.length || !matchesReady || preparing}
            onClick={() => void startImport()}
            className={PRIMARY_BUTTON_CLASS}
          >
            {preparing ? "Checking your contacts…" : selected.length ? importLabel : "Nothing selected to import"}
          </Button>
        )}
        {step === 4 && finished && (
          <Button onClick={onClose} className={PRIMARY_BUTTON_CLASS}>
            Back to Contacts
          </Button>
        )}
      </div>
    </Card>
  );
};

export default ContactImport;
