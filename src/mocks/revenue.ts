import { RevenueCheck, RevenueLine, TaxDeductKind, TaxDeductType, stampCheckAccounts, sumCents } from "@/types/revenue";

type Amount = [label: string, gross: number, net: number];

interface LineSpec {
  id: string;
  cc: string;
  property: string;
  well?: string;
  product: string;
  interest?: string;
  prod: string;
  pct: number;
  price: number;
  btu?: number;
  gross: [volume: number, value: number];
  owner: [volume: number, value: number];
  taxes: Amount[];
  deducts: Amount[];
  notation?: string;
}

const toEntries = (amounts: Amount[]) => amounts.map(([label, gross, net]) => ({ label, gross, net }));

const line = (spec: LineSpec): RevenueLine => {
  const taxes = toEntries(spec.taxes);
  const deducts = toEntries(spec.deducts);
  const [grossVolume, grossValue] = spec.gross;
  const [ownerVolume, ownerValue] = spec.owner;
  const grossTaxes = sumCents(taxes.map((t) => t.gross));
  const grossDeducts = sumCents(deducts.map((d) => d.gross));
  const ownerTaxes = sumCents(taxes.map((t) => t.net));
  const ownerDeducts = sumCents(deducts.map((d) => d.net));
  return {
    id: spec.id,
    operatorCc: spec.cc,
    propertyDescription: spec.property,
    wellId: null,
    wellLabel: spec.well ?? null,
    productCode: spec.product,
    interestType: spec.interest ?? "Royalty",
    ownerPercent: spec.pct,
    distributionPercent: spec.pct,
    prodDate: spec.prod,
    price: spec.price,
    btuFactor: spec.btu ?? null,
    grossVolume,
    grossValue,
    grossTaxes,
    grossDeducts,
    netValue: sumCents([grossValue, grossTaxes, grossDeducts]),
    ownerVolume,
    ownerValue,
    ownerTaxes,
    ownerDeducts,
    ownerNetValue: sumCents([ownerValue, ownerTaxes, ownerDeducts]),
    taxes,
    deducts,
    notation: spec.notation ?? "",
    incomeAccountId: null,
  };
};

